    o.append(("addsp", 48))
    o.append(("ret",))

    L("rt_str_from_int")
    o.append(("subsp", 16))
    o.append(("mov", "R6", "A0"))
    o.append(("set", "A0", 21))
    o.append(("call", "rt_alloc"))
    o.append(("spaddr", "R1", 0))
    o.append(("store", "RET", "R1", 0))
    o.append(("mov", "A0", "RET"))
    o.append(("set", "A1", 0))
    o.append(("mov", "A2", "R6"))
    o.append(("call", "rt_append_int"))
    o.append(("spaddr", "R1", 0))
    o.append(("load", "R5", "R1", 0))
    o.append(("sub", "RET2", "RET", "R5"))
